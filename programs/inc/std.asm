; ============================================================================
;  字符与行输出子过程
; ============================================================================

; ----------------------------------------------------------------------------
;  crlf：回车换行
; ----------------------------------------------------------------------------
crlf:
    push ax dx
    mov dl, 0Dh
    mov ah, 02h
    int 21h
    mov dl, 0Ah
    int 21h
    pop dx ax
    ret

; ----------------------------------------------------------------------------
;  putc：输出 DL 字符
; ----------------------------------------------------------------------------
putc:
    push ax
    mov ah, 02h
    int 21h
    pop ax
    ret

; ============================================================================
;  数字打印子过程
; ============================================================================

; ----------------------------------------------------------------------------
;  print_dec16：输出 AX 无符号十进制（无前导零）
; ----------------------------------------------------------------------------
print_dec16:
    push ax bx cx dx
    mov bx, 10
    xor cx, cx
.div:
    xor dx, dx
    div bx
    push dx
    inc cx
    test ax, ax
    jnz .div
.out:
    pop dx
    add dl, '0'
    call putc
    loop .out
    pop dx cx bx ax
    ret

; ----------------------------------------------------------------------------
;  print_hex16：输出 AX 十六进制（固定 4 位，小写字母）
; ----------------------------------------------------------------------------
print_hex16:
    push ax bx cx dx
    mov cx, 4
    mov bx, ax
.h:
    rol bx, 4
    mov ax, bx
    and al, 0Fh
    cmp al, 10
    jb .digit
    add al, 'A'-10
    jmp .out
.digit:
    add al, '0'
.out:
    mov dl, al
    call putc
    loop .h
    pop dx cx bx ax
    ret

; ----------------------------------------------------------------------------
;  print_hex8：输出 AL 十六进制（固定 2 位）
; ----------------------------------------------------------------------------
print_hex8:
    push ax bx
    mov bl, al
    mov al, bl
    shr al, 4
    call .one
    mov al, bl
    and al, 0Fh
    call .one
    pop bx ax
    ret
.one:
    cmp al, 10
    jb .d
    add al, 'A'-10
    jmp .o
.d:
    add al, '0'
.o:
    mov dl, al
    call putc
    ret

; ----------------------------------------------------------------------------
;  print_bits16：输出 AX 十六位二进制（每 4 位留一空格）
; ----------------------------------------------------------------------------
print_bits16:
    push ax bx cx dx
    mov cx, 16
    mov bx, ax
.h:
    rol bx, 1
    mov ax, bx
    and al, 1
    add al, '0'
    mov dl, al
    call putc
    ; 每 4 位插一空格
    mov ax, cx
    and ax, 3
    jnz .no
    push ax cx
    mov dl, ' '
    call putc
    pop cx ax
.no:
    loop .h
    pop dx cx bx ax
    ret

; ============================================================================
;  延时与按键子过程
; ============================================================================

; ----------------------------------------------------------------------------
;  delay_ticks：延时 CX 个时钟滴答（约 18.2 滴答/秒）
; ----------------------------------------------------------------------------
delay_ticks:
    push ax dx
    mov ah, 0
    int 1Ah
    add dx, cx
    mov ax, dx              ; 目标低 16 位
.t:
    mov ah, 0
    int 1Ah
    cmp dx, ax
    jne .t
    pop dx ax
    ret

; ----------------------------------------------------------------------------
;  get_key：读一个键盘字符（无回显），AL=字符；扩展键返回 0
; ----------------------------------------------------------------------------
get_key:
    push ax bx
    xor ah, ah
    int 16h
    test al, al
    jnz .done
    xor ax, ax
    int 16h                 ; 吃掉扫描码
    xor al, al
.done:
    pop bx ax
    ret

; ----------------------------------------------------------------------------
;  wait_key：等待任意键并回调 Enter 提示字符
; ----------------------------------------------------------------------------
wait_key:
    push ax dx
    mov dl, ':'
    mov ah, 02h
    int 21h
    call get_key
    pop dx ax
    ret

; ============================================================================
;  十进制字符串解析
; ============================================================================

; ----------------------------------------------------------------------------
;  atoi_dec：DS:SI 十进制字符串 → AX
;  边界：最大 65535；非数字字符结束
; ----------------------------------------------------------------------------
atoi_dec:
    push bx cx dx si
    xor ax, ax
    mov bx, 10
.loop:
    mov cl, [si]
    cmp cl, '0'
    jb .done
    cmp cl, '9'
    ja .done
    xor ch, ch
    and cl, 0Fh
    mul bx                  ; AX*10
    add ax, cx               ; + digit
    inc si
    jmp .loop
.done:
    pop si dx cx bx
    ret

; ============================================================================
;  简易数字输入
; ============================================================================

; 共享输入缓冲（供 read_num 使用）
num_buf:
    db 8                    ; 最大长度
    db 0                    ; 实际长度（AH=0A 填充）
    db 8 dup(0)             ; 数据区

; ----------------------------------------------------------------------------
;  read_num：打印 DS:DX 提示后读入一个无符号十进制数 → AX
; ----------------------------------------------------------------------------
read_num:
    push ax cx si dx
    mov ah, 09h
    int 21h                 ; 输出提示
    mov dx, num_buf
    mov ah, 0Ah
    int 21h                 ; 缓冲输入
    call crlf
    lea si, [num_buf+2]
    call atoi_dec
    pop dx si cx ax
    ret

; ============================================================================
;  命令行参数解析
; ============================================================================

arg_need db 0               ; 需要的参数序号
arg_len  dw 0               ; 命令行长度（PSP+80h）
arg_found db 0              ; 是否找到

; ----------------------------------------------------------------------------
;  arg_end_check：检测数据指针 SI 是否已越过命令行末尾
;  出口：CF=1 表示已到末尾
; ----------------------------------------------------------------------------
arg_end_check:
    mov ax, si
    sub ax, 0081h
    cmp ax, [arg_len]
    jb .inside
    stc
    ret
.inside:
    clc
    ret

; ----------------------------------------------------------------------------
;  get_cmd_arg：取命令行第 BL 个参数（1 起）到 DS:DI，0 结尾
;  出口：CF=0 成功；CF=1 参数不足
; ----------------------------------------------------------------------------
get_cmd_arg:
    push ax bx cx si di
    mov [arg_need], bl
    mov cl, [0080h]
    xor ch, ch
    mov [arg_len], cx
    mov si, 0081h
    mov bx, 1               ; 当前 token 序号
    mov byte [arg_found], 0
.scan:
    ; 跳过前导空格
.skip:
    call arg_end_check
    jc .finish
    cmp byte [si], ' '
    jne .have
    inc si
    jmp .skip
.have:
    cmp bl, [arg_need]
    jne .skip_tok
    ; 拷贝当前 token 到 DI
.cpy:
    call arg_end_check
    jc .cpy_end
    cmp byte [si], ' '
    je .cpy_end
    mov al, [si]
    mov [di], al
    inc si
    inc di
    jmp .cpy
.cpy_end:
    mov byte [di], 0
    mov byte [arg_found], 1
    jmp .finish
.skip_tok:
    ; 跳过当前 token
.st:
    call arg_end_check
    jc .next_tok
    cmp byte [si], ' '
    je .next_tok
    inc si
    jmp .st
.next_tok:
    inc bx
    jmp .scan
.finish:
    cmp byte [arg_found], 0
    je .fail
    clc
    jmp .done
.fail:
    stc
.done:
    pop di si cx bx ax
    ret

; ============================================================================
;  BIOS 光标定位
; ============================================================================

; ----------------------------------------------------------------------------
;  setcurs：把光标定位到 (DH=行, DL=列)，页号 0
; ----------------------------------------------------------------------------
setcurs:
    push ax bx dx
    mov ah, 02h
    mov bh, 0
    int 10h
    pop dx bx ax
    ret