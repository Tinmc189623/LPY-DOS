; ----------------------------------------------------------------------------
;  宏：输出 $ 结尾字符串（AH=09），str 为段内标签
; ----------------------------------------------------------------------------
macro puts str {
    mov dx, str
    mov ah, 09h
    int 21h
}

; ----------------------------------------------------------------------------
;  宏：输出单个字符（立即数，AH=02）
; ----------------------------------------------------------------------------
macro putch ch {
    mov dl, ch
    mov ah, 02h
    int 21h
}