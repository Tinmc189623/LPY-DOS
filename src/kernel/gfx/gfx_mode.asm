; ============================================================================
;  模式切换
; ============================================================================

; ----------------------------------------------------------------------------
;  fn_gfx_init：进入 VGA13h 图形模式（AH=70）
; ----------------------------------------------------------------------------
fn_gfx_init:
        cmp byte [gfx_on], 0
        jne .already
        ; 记录当前视频模式
        mov ah, 0Fh
        int 10h
        mov [gfx_old_mode], al
        ; 切换 VGA 13h（320x200x256）
        mov ax, 13h
        int 10h
        mov byte [gfx_on], 1
.already:
        clc
        ret

; ----------------------------------------------------------------------------
;  fn_gfx_exit：恢复文本模式（AH=71）
; ----------------------------------------------------------------------------
fn_gfx_exit:
        mov ax, 0003h
        int 10h
        mov byte [gfx_on], 0
        clc
        ret

; ----------------------------------------------------------------------------
;  gfx_terminate：程序终止路径调用——若处于图形模式则恢复文本
; ----------------------------------------------------------------------------
gfx_terminate:
        cmp byte [gfx_on], 0
        je .ret
        push ax bx cx dx es
        mov ax, 0003h
        int 10h
        mov byte [gfx_on], 0
        pop es dx cx bx ax
.ret:
        ret

